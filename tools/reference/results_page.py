"""Build the results page, and VALIDATION.md's Official counts table, from the checkers' results.

usage: results_page.py [--out PATH] [--validation check|write]

Reads results/jurisdictions.json (each jurisdiction's name, what it is checked against, the figures of the two
checked only by the Java tests, which of a checker's contests count, the known differences, the US rules table
and the rows of VALIDATION.md's table) and results/<name>.json, which each checker writes with --results
(`python3 tools/reference/nyc/check.py nyc-data --results tools/reference/results/nyc.json`; also aec, nsw,
cambridge, and Scotland's check.py as scotland, stage_report.py as scotland-stage-reports and stages.py as
scotland-wikipedia), and writes results/real-elections.html, a self-contained page with results/page.css inlined.
A contest that doesn't match every round, or elects differently, and that no difference in the jurisdictions file
names is shown as unexplained, and so is reported here; a difference naming a contest that now matches is reported
too.

With --validation write, it rewrites VALIDATION.md's Official counts table instead, between its markers; with
--validation check, it fails if the table there isn't what the results give (the Python tests run this).
"""
import argparse
import difflib
import html
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(HERE, "results")
VALIDATION = os.path.join(HERE, "..", "..", "VALIDATION.md")
BEGIN = ("<!-- Generated by tools/reference/results_page.py --validation write, from tools/reference/results: "
         "edit those, not this table. -->")
END = "<!-- End of the generated table. -->"


def esc(text):
    return html.escape(str(text), quote=True)


def number(n):
    return f"{n:,}"


def load_checker(name, scope=None):
    """A checker's results, only the contests its scope (a pattern on their ids) takes in, where it has one."""
    with open(os.path.join(RESULTS, name + ".json"), encoding="utf-8") as source:
        results = json.load(source)
    if scope:
        results["contests"] = [c for c in results["contests"] if re.search(scope["pattern"], c["contest"])]
    return results


def is_exact(contest):
    return contest["rounds"] is not None and contest["matched"] == contest["rounds"]


def is_short(contest):
    """Not exact where rounds are compared, or electing differently."""
    return (contest["rounds"] is not None and contest["matched"] < contest["rounds"]) or not contest["winners_same"]


def confirmed(data):
    """(checker, contest) pairs whose winners a difference marks as confirmed by hand."""
    return {(d["checker"], c) for d in data["differences"] if d.get("winners_confirmed") for c in d["contests"]}


def checker_figures(name, checked, data):
    """contests, every_round, with_rounds, winners_same, short and rounds_total of one checker's results."""
    contests = checked[name]["contests"]
    with_rounds = [c for c in contests if c["rounds"] is not None]
    by_hand = confirmed(data)
    every = sum(map(is_exact, with_rounds))
    winners = sum(c["winners_same"] or (name, c["contest"]) in by_hand for c in contests)
    passing = sum(c["ok"] or (name, c["contest"]) in by_hand for c in contests)
    return {"contests": len(contests), "every_round": every, "with_rounds": len(with_rounds),
            "winners_same": winners, "short": len(with_rounds) - every,
            "rounds_total": sum(c["rounds"] for c in with_rounds), "winners_only": len(contests) - len(with_rounds),
            "winners": share(winners, len(contests)), "passing": share(passing, len(contests))}


def share(part, whole):
    """"all 93", or "89 of 93"."""
    return f"all {number(whole)}" if part == whole else f"{number(part)} of {number(whole)}"


def figures(jurisdiction, checked, data):
    if "fixed" in jurisdiction:
        return dict(jurisdiction["fixed"], rounds_total=None)
    return checker_figures(jurisdiction["checker"], checked, data)


def fill(text, checked, data):
    """A text with {checker.field} filled from that checker's figures, with thousands separators."""
    def figure(match):
        value = checker_figures(match.group(1), checked, data)[match.group(2)]
        return value if isinstance(value, str) else number(value)
    return re.sub(r"\{([\w-]+)\.(\w+)\}", figure, text)


def referenced(data):
    """Every checker the page reads: those of the jurisdictions and those its texts name."""
    names = [j["checker"] for g in data["groups"] for j in g["jurisdictions"] if "checker" in j]
    texts = json.dumps(data)
    for name in re.findall(r"\{([\w-]+)\.\w+\}", texts):
        if name not in names:
            names.append(name)
    return names


def result_cell(jurisdiction, f, single_seat, checked, data):
    if "chip" in jurisdiction:
        all_rounds = not f["with_rounds"] or f["every_round"] == f["with_rounds"]
        kind = jurisdiction.get("kind") or ("exact" if f["winners_same"] == f["contests"] and all_rounds else "near")
        return (f'<span class="chip {kind}">{esc(fill(jurisdiction["chip"], checked, data))}</span>'
                f'<p>{esc(fill(jurisdiction["text"], checked, data))}</p>')
    if single_seat:
        winners = "all " + number(f["contests"]) if f["winners_same"] == f["contests"] else number(f["winners_same"])
        share = 100 * f["every_round"] / f["contests"]
        return (f'<div class="meter"><span class="bar"><i style="width: {share:.1f}%"></i></span>'
                f'<span class="mono">{f["every_round"]} / {f["contests"]}</span></div>'
                f'<p>Every round in {number(f["every_round"])}; eliminations and winner in {winners}.</p>')
    precision = jurisdiction.get("precision", "")
    kind = "exact" if f["every_round"] == f["with_rounds"] == f["contests"] == f["winners_same"] else "near"
    if f["every_round"] == f["with_rounds"] == f["contests"]:
        label = "Every round"
    elif f["every_round"] == f["with_rounds"]:
        label = f'Every round of {number(f["with_rounds"])}'
    else:
        label = f'Every round in {number(f["every_round"])} of {number(f["with_rounds"])}'
    chip = f'<span class="chip {kind}">{label}</span>'
    text = (f'{number(f["rounds_total"])} rounds, {precision}.' if f["rounds_total"]
            else precision[0].upper() + precision[1:] + ".")
    if f["with_rounds"] < f["contests"]:
        text += f' {f["contests"] - f["with_rounds"]} checked by winners only.'
    if f["winners_same"] == f["contests"]:
        text += " The same winners in all." if f["contests"] > 1 else ""
    else:
        text += f' The same winners in {number(f["winners_same"])}.'
    return chip + f"<p>{esc(text)}</p>"


def register(data, checked):
    rows = []
    for group in data["groups"]:
        rows.append(f'<tr class="group"><td colspan="5">{esc(group["name"])}</td></tr>')
        for j in group["jurisdictions"]:
            f = figures(j, checked, data)
            ruleset = f'<code>{esc(j["ruleset"])}</code>' if j["ruleset"] else "—"
            rows.append(
                f'<tr><td class="place">{esc(j["name"])}<small>{esc(j["years"])}</small></td>'
                f'<td class="num">{number(f["contests"])}</td><td>{ruleset}</td>'
                f'<td class="what">{esc(j["against"])}</td>'
                f'<td><div class="result">{result_cell(j, f, group.get("single_seat", False), checked, data)}'
                '</div></td></tr>')
    return "\n".join(rows)


def differences(data, checked):
    """The cause cards, the unexplained contests among them, and warnings for the generator's caller."""
    every = {d["checker"] for d in data["differences"] if d.get("contests") == "all"}
    named = {(d.get("checker"), c) for d in data["differences"] if d.get("contests") != "all"
             for c in d.get("contests", [])}
    warnings, unexplained = [], []
    for name, results in checked.items():
        by_id = {c["contest"]: c for c in results["contests"]}
        for c in results["contests"]:
            if is_short(c) and (name, c["contest"]) not in named and name not in every:
                unexplained.append(f'{name} {c["contest"]}: {c["line"]}')
        for checker, contest in named:
            if checker == name and contest in by_id and not is_short(by_id[contest]) \
                    and not any(d["cause"] == "source" for d in data["differences"]
                                if d.get("contests") != "all" and contest in d.get("contests", [])):
                warnings.append(f"{name} {contest} is named as a difference but now matches every round")
            if checker == name and contest not in by_id:
                warnings.append(f"{name} {contest} is named as a difference but isn't among the checker's contests")
    cards = []
    for cause in data["causes"]:
        items = [fill(d["text"], checked, data) for d in data["differences"] if d["cause"] == cause["id"]]
        cards.append(f'<div class="cause"><h3>{esc(cause["title"])}</h3><p class="why">{esc(cause["why"])}</p>'
                     f'<ul>{"".join(f"<li>{esc(i)}</li>" for i in items)}</ul></div>')
    if unexplained:
        cards.append('<div class="cause unexplained"><h3>Not yet explained</h3>'
                     '<p class="why">Contests the checkers report short of every round, with no cause recorded.</p>'
                     f'<ul>{"".join(f"<li>{esc(u)}</li>" for u in unexplained)}</ul></div>')
    return "\n".join(cards), unexplained, warnings


def example(data):
    ex = data["example"]
    official = {r["ours"]: r["official"] for r in ex["rounds"]}
    columns = range(0, ex["our_rounds"] + 1)
    top = "".join(f'<span class="cell on">{official[k]}</span>' if k in official else '<span class="cell"></span>'
                  for k in columns)
    links = "".join('<span class="cell on"></span>' if k in official else '<span class="cell"></span>' for k in columns)
    ours = "".join(f'<span class="cell{" hit" if k in official else ""}">{"1st" if k == 0 else k}</span>'
                   for k in columns)
    described = "; ".join(f'official round {r["official"]} matches '
                          + ("the record's first choices" if r["ours"] == 0 else f'this count\'s round {r["ours"]}')
                          for r in ex["rounds"])
    cards = "".join(f'<div><b>{esc(r["label"])}</b><span>{esc(r["text"])}</span>'
                    f'<span class="mono">{esc(r["figures"])}</span>'
                    + (f'<span>{esc(r["after"])}</span>' if r.get("after") else "") + "</div>" for r in ex["rounds"])
    return (f'<section aria-labelledby="example-h"><header><h2 id="example-h">{esc(ex["title"])}</h2>'
            f'<p>{esc(ex["intro"])}</p></header><div class="example">'
            f'<div class="lanes" role="img" aria-label="{esc(described.capitalize())}."><div class="lane-grid">'
            f'<div class="official"><span class="lane-name">Official rounds</span>{top}</div>'
            f'<div class="link-row"><span class="lane-name"></span>{links}</div>'
            f'<div class="ours"><span class="lane-name">This count</span>{ours}</div>'
            f'</div></div><div class="figures">{cards}</div></div></section>')


def rules(data):
    head = "".join(f"<th>{esc(c)}</th>" for c in data["rules"]["columns"])
    body = []
    for row in data["rules"]["rows"]:
        *cells, options = row
        option = "its own converter" if options is None else (f"<code>{esc(options)}</code>" if options else "defaults")
        body.append("<tr>" + "".join(f"<td>{esc(c)}</td>" for c in cells) + f'<td class="opt">{option}</td></tr>')
    return f"<thead><tr>{head}</tr></thead><tbody>{''.join(body)}</tbody>"


def build(data, checked, css, stamp):
    totals = [figures(j, checked, data) for g in data["groups"] for j in g["jurisdictions"]]
    contests = sum(f["contests"] for f in totals)
    winners = sum(f["winners_same"] for f in totals)
    jurisdictions = len(totals)
    cards, unexplained, warnings = differences(data, checked)
    differ = contests - winners
    exception = (f'{number(differ)} contest{"" if differ == 1 else "s"} elect{"s" if differ == 1 else ""} differently: '
                 "see Known differences. ") if differ else ""
    page = f"""<title>Real Elections Recounted</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@75..100,500..800&family=Public+Sans:ital,wght@0,400;0,600;1,400&family=IBM+Plex+Mono:wght@400;500&display=swap">
<style>
{css}</style>
<!-- Generated by tools/reference/results_page.py from tools/reference/results; edit those, not this file. -->
<div class="wrap">

<header class="masthead">
  <div>
    <div class="label">rankedchoice · validation against official counts</div>
    <h1>Real elections, recounted from their ballots</h1>
    <p class="lede">The calculator is run on the published ballots of real elections, under each jurisdiction's own rules, and every official round is compared with its count: candidate by candidate, to the precision the official count gives.</p>
  </div>
  <div>
    <div class="tally">
      <div><strong>{number(contests)}</strong><span>contests in {jurisdictions} jurisdictions</span></div>
      <div><strong>{number(winners)}</strong><span>elect the official winners</span></div>
    </div>
    <p class="stamp">{esc(exception)}{esc(stamp)}</p>
  </div>
</header>

<section aria-labelledby="register-h">
  <header>
    <h2 id="register-h">Jurisdictions</h2>
    <p>"Every round" means every candidate's votes in every official round, at the official precision. Where a contest falls short, the reason is under <a href="#differences">Known differences</a>.</p>
  </header>
  <div class="register">
    <table>
      <thead>
        <tr><th>Jurisdiction</th><th class="num">Contests</th><th>Ruleset</th><th>Checked against</th><th>Result</th></tr>
      </thead>
      <tbody>
{register(data, checked)}
      </tbody>
    </table>
  </div>
</section>

{example(data)}

<section id="differences" aria-labelledby="differences-h">
  <header>
    <h2 id="differences-h">Known differences</h2>
    <p>Every figure that doesn't match, by cause. In each the same candidates are eliminated, in the same order, and the same candidates win, unless it says otherwise.</p>
  </header>
  <div class="causes">
{cards}
  </div>
</section>

<section class="rules" aria-labelledby="rules-h">
  <header>
    <h2 id="rules-h">How US ranked-choice counts read ballots</h2>
    <p>The rules that differ between the US counts, each found by matching the official rounds. One converter reads them all, one option per rule; Portland's ballot record has a different shape and its own converter.</p>
  </header>
  <div class="register">
    <table>
{rules(data)}
    </table>
  </div>
</section>

<footer class="notes">
  <p>Ballots come from the jurisdictions themselves, from FairVote's collections of cast vote records (Harvard Dataverse), and for Scotland from MGGG's scot-elex. Official results come from each election authority's own reports, or the Internet Archive's copies where the authority no longer publishes them.</p>
  <p>The full evidence for every figure, and the scripts that reproduce each check, are in the project's VALIDATION.md and tools/reference.</p>
</footer>

</div>
"""
    return page, unexplained, warnings


def validation_table(data, checked):
    """VALIDATION.md's "Official counts" table, its figures filled from the checkers' results."""
    table = data["validation_table"]
    lines = ["| " + " | ".join(table["columns"]) + " |", "|" + "---|" * len(table["columns"])]
    for row in table["rows"]:
        lines.append("| " + " | ".join(fill(cell, checked, data) for cell in row) + " |")
    return "\n".join(lines)


def with_table(text, table):
    """VALIDATION.md's text with the table between the markers replaced."""
    start, end = text.index(BEGIN) + len(BEGIN), text.index(END)
    return text[:start] + "\n" + table + "\n" + text[end:]


def load(data=None):
    """The jurisdictions file and every checker's results it reads."""
    if data is None:
        with open(os.path.join(RESULTS, "jurisdictions.json"), encoding="utf-8") as source:
            data = json.load(source)
    return data, {name: load_checker(name, data.get("scope", {}).get(name)) for name in referenced(data)}


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", default=os.path.join(RESULTS, "real-elections.html"))
    parser.add_argument("--validation", choices=["check", "write"],
                        help="instead of the page, check VALIDATION.md's Official counts table against the results, "
                             "or rewrite it")
    args = parser.parse_args()
    data, checked = load()
    if args.validation:
        with open(VALIDATION, encoding="utf-8") as source:
            text = source.read()
        updated = with_table(text, validation_table(data, checked))
        if args.validation == "write":
            with open(VALIDATION, "w", encoding="utf-8") as out:
                out.write(updated)
            print("wrote VALIDATION.md's Official counts table")
        elif updated != text:
            sys.stdout.writelines(difflib.unified_diff(text.splitlines(True), updated.splitlines(True),
                                                       "VALIDATION.md", "from the results"))
            sys.exit("VALIDATION.md's Official counts table doesn't match the results: run with --validation write")
        else:
            print("VALIDATION.md's Official counts table matches the results")
        return
    with open(os.path.join(RESULTS, "page.css"), encoding="utf-8") as source:
        css = source.read()
    newest = max(results["date"] for results in checked.values())
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=HERE, capture_output=True,
                            text=True).stdout.strip()
    fixed = [j for g in data["groups"] for j in g["jurisdictions"] if "fixed" in j]
    stamp = (f"Checks run up to {newest}" + (f", at commit {commit}" if commit else "") + "; "
             + "; ".join(f'{j["name"]} from {j["source"]}' for j in fixed) + ".")
    page, unexplained, warnings = build(data, checked, css, stamp)
    with open(args.out, "w", encoding="utf-8") as out:
        out.write(page)
    for line in unexplained:
        print(f"unexplained: {line}", file=sys.stderr)
    for line in warnings:
        print(f"warning: {line}", file=sys.stderr)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
